-- ------------------------------------------------------------ worker: messaggi e push
create or replace function worker_claim_msgs(p_limit int default 30) returns jsonb language plpgsql security definer set search_path = public as $$
declare v jsonb;
begin
  -- promemoria push (oltre a WhatsApp): stessa finestra di reminder_hours, una volta sola per lezione
  insert into msg_outbox(kind, student_id, params)
  select 'push', b.student_id, jsonb_build_object('title', 'Promemoria lezione',
           'body', format('%s · %s con %s. Tocca per confermare.', initcap(_when(b.date, b.hour, b.start_min)), r.name, t.name),
           'url', coalesce(_setting('public_url'), '') || '#lezioni', 'tag', 'promemoria-' || b.id, 'reminder_for', b.id)
    from bookings b join rooms r on r.id = b.room_id join teachers t on t.id = b.teacher_id
   where b.status = 'confermata' and b.date between _today() and _today() + 3
     and _slot_start(b.date, b.hour) between now() + interval '30 minutes' and now() + make_interval(hours => _setting_int('reminder_hours'))
     and exists (select 1 from push_subs p where p.student_id = b.student_id and p.gone_at is null)
     and not exists (select 1 from msg_outbox m where m.kind = 'push' and (m.params->>'reminder_for')::bigint = b.id);

  with c as (
    select id from msg_outbox where done_at is null and next_at <= now() and attempts < 6 order by id limit p_limit for update skip locked),
  u as (
    update msg_outbox o set attempts = o.attempts + 1, next_at = now() + make_interval(mins => least((2 ^ o.attempts)::int * 2, 240))
      from c where o.id = c.id returning o.id, o.kind, o.student_id, o.params)
  select coalesce(jsonb_agg(jsonb_build_object('id', u.id, 'kind', u.kind, 'params', u.params,
      'student', (select jsonb_build_object('id', s.id, 'name', s.name, 'phone', s.phone, 'wa_consent', s.wa_consent) from students s where s.id = u.student_id),
      'subs', (select coalesce(jsonb_agg(jsonb_build_object('endpoint', p.endpoint, 'p256dh', p.p256dh, 'auth', p.auth)), '[]')
               from push_subs p where p.student_id = u.student_id and p.gone_at is null),
      'teacher', (select name from teachers where id = (u.params->>'teacher_id')::bigint)) order by u.id), '[]')
    into v from u;
  return v;
end $$;

