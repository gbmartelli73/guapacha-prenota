-- ------------------------------------------------------------ punti fedeltà
-- punti = lezioni svolte (passate, non annullate, non segnate assenti) × punti_per_lezione + movimenti manuali
alter table bookings add column if not exists attendance text check (attendance in ('presente', 'assente'));
create table if not exists points_ledger (
  id bigint generated by default as identity primary key,
  student_id bigint not null references students(id) on delete cascade,
  delta int not null, reason text not null check (reason in ('premio', 'rettifica')),
  note text not null default '', created_at timestamptz not null default now(), created_by uuid
);
create index if not exists points_ledger_student on points_ledger(student_id);

create or replace function _lessons_done(p_student bigint) returns int language sql stable security definer set search_path = public as $$
  select count(*)::int from bookings
   where student_id = p_student and status = 'confermata' and coalesce(attendance, '') <> 'assente'
     and _slot_start(date, hour) + interval '1 hour' <= now()
$$;

create or replace function _points(p_student bigint) returns jsonb language sql stable security definer set search_path = public as $$
  with x as (select _lessons_done(p_student) as lessons,
                    coalesce((select sum(delta) from points_ledger where student_id = p_student), 0)::int as manual,
                    coalesce((select -sum(delta) from points_ledger where student_id = p_student and reason = 'premio'), 0)::int as redeemed)
  select jsonb_build_object('lessons_done', lessons, 'per_lesson', coalesce(_setting_int('points_per_lesson'), 10),
    'total', lessons * coalesce(_setting_int('points_per_lesson'), 10) + manual, 'redeemed', redeemed,
    'reward', coalesce(nullif(_setting_int('points_reward'), 0), 100), 'reward_label', _setting('points_reward_label'))
  from x
$$;

