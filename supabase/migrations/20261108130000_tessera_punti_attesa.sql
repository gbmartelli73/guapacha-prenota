create or replace function admin_waitlist_status(p_id bigint, p_status text) returns jsonb language plpgsql security definer set search_path = public as $$
declare w waitlist;
begin
  perform _require_staff();
  if p_status not in ('attiva', 'avvisato', 'prenotato', 'annullata') then perform _err('Stato non valido.'); end if;
  update waitlist set status = p_status where id = p_id returning * into w;
  if not found then perform _err('Richiesta non trovata.'); end if;
  return jsonb_build_object('ok', true);
end $$;

-- avvisa a mano chi è in lista (es. quando la segreteria libera un posto)
create or replace function admin_waitlist_notify(p_id bigint) returns jsonb language plpgsql security definer set search_path = public as $$
declare w waitlist;
begin
  perform _require_staff();
  update waitlist set status = 'avvisato', notified_at = now() where id = p_id and status in ('attiva', 'avvisato') returning * into w;
