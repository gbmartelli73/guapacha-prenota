  select case when d <= x then x else (x + interval '1 year')::date end
  from (select make_date(extract(year from d)::int, split_part(coalesce(nullif(_setting('season_end'), ''), '08-31'), '-', 1)::int,
                         split_part(coalesce(nullif(_setting('season_end'), ''), '08-31'), '-', 2)::int) as x) s
$$;

