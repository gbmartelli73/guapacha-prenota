-- ------------------------------------------------------------ WhatsApp: risposta ai pulsanti del promemoria
create or replace function bot_booking_action(p_phone text, p_booking bigint, p_action text) returns jsonb
language plpgsql security definer set search_path = public as $$
declare s students; b bookings;
begin
  select * into s from students where phone = _norm_phone(p_phone);
  select * into b from bookings where id = p_booking and student_id = s.id;
  if s.id is null or b.id is null then return jsonb_build_object('errore', 'Lezione non trovata.'); end if;
  if b.status <> 'confermata' then return jsonb_build_object('errore', 'Questa lezione è già stata annullata.'); end if;
  if p_action = 'conferma' then
    update bookings set student_confirmed_at = coalesce(student_confirmed_at, now()) where id = b.id;
    return jsonb_build_object('confermata', true, 'quando', _when(b.date, b.hour, b.start_min), 'sala', (select name from rooms where id = b.room_id));
  elsif p_action = 'annulla' then
    perform _cancel_booking(b.id, 'whatsapp', s.id);
    return jsonb_build_object('annullata', true, 'quando', _when(b.date, b.hour, b.start_min));
  end if;
  return jsonb_build_object('errore', 'Azione non valida.');
exception when sqlstate 'P0001' then return jsonb_build_object('errore', sqlerrm);
end $$;

-- assistente (WhatsApp e app): nuovi strumenti sposta, lista d'attesa, tessera, conferma
create or replace function assistant_tool(p_phone text, p_tool text, p_input jsonb, p_channel text default 'whatsapp') returns jsonb
language plpgsql security definer set search_path = public as $$
declare s students; t teachers; b jsonb; g jsonb; v_date date; v_hour int; v_room bigint; v_bk bookings; v_src text := case when p_channel = 'app' then 'app' else 'whatsapp' end;
begin
  select * into s from students where phone = _norm_phone(p_phone);
  if not found then perform bot_student(p_phone); select * into s from students where phone = _norm_phone(p_phone); end if;

  if p_tool = 'prenota' and v_src = 'app' then
    -- come bot_tool ma con origine "app"
    if s.name = '' then return jsonb_build_object('errore', 'Prima chiedi nome e cognome all''allievo e salvali con salva_nome.'); end if;
    t := _find_teacher(p_input->>'insegnante');
    if t.id is null then return jsonb_build_object('errore', format('Nessun insegnante di nome %s.', p_input->>'insegnante')); end if;
    v_date := (p_input->>'data')::date; v_hour := (p_input->>'ora')::int;
    g := _day_grid(v_date);
    select (c->>'room_id')::bigint into v_room from jsonb_array_elements(g->'cells') c join rooms r on r.id = (c->>'room_id')::bigint
     where (c->>'hour')::int = v_hour and c->>'status' = 'free' and c->'teachers' @> to_jsonb(t.id)
       and (coalesce(p_input->>'sala', '') = '' or r.name ~* ('(^|\D)' || (p_input->>'sala') || '(\D|$)')) order by r.sort limit 1;
    if v_room is null then return jsonb_build_object('errore', format('%s non è disponibile %s alle %s.', t.name, _fmt_date(v_date), _fmt_hour(v_hour))); end if;
    b := _create_booking(v_date, v_hour, v_room, t.id, s.id, coalesce(p_input->>'nota', ''), 'app', false, false);
    return jsonb_build_object('prenotata', true, 'codice', b->'id', 'giorno', _fmt_date(v_date), 'ora', _fmt_hour(v_hour), 'sala', b->'room', 'insegnante', b->'teacher');

  elsif p_tool = 'annulla' and v_src = 'app' then
    b := _cancel_booking((p_input->>'codice')::bigint, 'allievo', s.id);
    return jsonb_build_object('annullata', true, 'giorno', _fmt_date((b->>'date')::date), 'ora', _fmt_hour((b->>'hour')::int), 'sala', b->'room');

  elsif p_tool = 'sposta' then
    select * into v_bk from bookings where id = (p_input->>'codice')::bigint and student_id = s.id and status = 'confermata';
    if v_bk.id is null then return jsonb_build_object('errore', 'Lezione non trovata: usa il codice di le_mie_lezioni.'); end if;
    if coalesce(p_input->>'insegnante', '') <> '' then
      t := _find_teacher(p_input->>'insegnante');
      if t.id is null then return jsonb_build_object('errore', format('Nessun insegnante di nome %s.', p_input->>'insegnante')); end if;
    else select * into t from teachers where id = v_bk.teacher_id; end if;
    v_date := (p_input->>'data')::date; v_hour := (p_input->>'ora')::int;
    g := _day_grid(v_date);
    select (c->>'room_id')::bigint into v_room from jsonb_array_elements(g->'cells') c join rooms r on r.id = (c->>'room_id')::bigint
     where (c->>'hour')::int = v_hour and c->>'status' = 'free' and c->'teachers' @> to_jsonb(t.id)
     order by ((c->>'room_id')::bigint = v_bk.room_id) desc, r.sort limit 1;
    if v_room is null then return jsonb_build_object('errore', format('%s non è disponibile %s alle %s.', t.name, _fmt_date(v_date), _fmt_hour(v_hour))); end if;
    b := _move_booking(v_bk.id, v_date, v_hour, v_room, t.id, v_src, s.id, false);
    return jsonb_build_object('spostata', true, 'giorno', _fmt_date(v_date), 'ora', _fmt_hour(v_hour), 'sala', b->'room', 'insegnante', b->'teacher');

  elsif p_tool = 'lista_attesa' then
    if coalesce(p_input->>'insegnante', '') <> '' then
      t := _find_teacher(p_input->>'insegnante');
      if t.id is null then return jsonb_build_object('errore', format('Nessun insegnante di nome %s.', p_input->>'insegnante')); end if;
    end if;
    b := _waitlist_add(s.id, (p_input->>'data')::date, (p_input->>'ora')::int, t.id, v_src);
    return jsonb_build_object('in_lista', true, 'giorno', _fmt_date((p_input->>'data')::date), 'ora', _fmt_hour((p_input->>'ora')::int),
      'nota', 'Avviseremo l''allievo appena si libera un posto (WhatsApp e notifica sul telefono).');

  elsif p_tool = 'tessera' then
    return jsonb_build_object('tessera', _card(s) - 'card_token' - 'tax_code' - 'birth_date' - 'address');

  elsif p_tool = 'conferma' then
    update bookings set student_confirmed_at = coalesce(student_confirmed_at, now())
     where id = (p_input->>'codice')::bigint and student_id = s.id and status = 'confermata';
    if not found then return jsonb_build_object('errore', 'Lezione non trovata.'); end if;
    return jsonb_build_object('confermata', true);
  end if;
  return bot_tool(p_phone, p_tool, p_input);
exception
  when sqlstate 'P0001' then return jsonb_build_object('errore', sqlerrm);
  when invalid_datetime_format or datetime_field_overflow or invalid_text_representation then return jsonb_build_object('errore', 'Data o ora non valida: usa AAAA-MM-GG e un''ora intera.');
end $$;

