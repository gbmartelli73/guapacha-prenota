-- push: accoda una notifica per un allievo (solo se ha attivato le notifiche)
create or replace function _push(p_student bigint, p_title text, p_body text, p_url text default '', p_tag text default '') returns void
language plpgsql security definer set search_path = public as $$
begin
  if exists (select 1 from push_subs where student_id = p_student and gone_at is null) then
    insert into msg_outbox(kind, student_id, params)
    values ('push', p_student, jsonb_build_object('title', p_title, 'body', p_body, 'url', p_url, 'tag', p_tag));
  end if;
end $$;

create or replace function _when(d date, h int, m int default 0) returns text language sql stable security definer set search_path = public as
$$ select _fmt_date(d) || ' alle ' || lpad(h::text, 2, '0') || ':' || lpad(coalesce(m, 0)::text, 2, '0') $$;

-- ------------------------------------------------------------ eventi sulle lezioni: lista d'attesa e push
create or replace function _waitlist_freed(p_date date, p_hour int, p_teacher bigint, p_student bigint) returns void
language plpgsql security definer set search_path = public as $$
declare w record; v_url text := _setting('public_url');
begin
  if _slot_start(p_date, p_hour) <= now() then return; end if;
  for w in update waitlist set status = 'avvisato', notified_at = now()
            where date = p_date and hour = p_hour and status = 'attiva' and student_id <> p_student
              and (teacher_id is null or teacher_id = p_teacher)
           returning id, student_id loop
    insert into msg_outbox(kind, student_id, params)
      select 'wl_free', w.student_id, jsonb_build_object('date', p_date, 'hour', p_hour, 'waitlist_id', w.id)
      from students where id = w.student_id and wa_consent;
    perform _push(w.student_id, 'Si è liberato un posto!', format('%s: prenota subito dall''app.', initcap(_when(p_date, p_hour))),
                  coalesce(v_url, '') || '#giorno=' || p_date, 'attesa-' || w.id);
  end loop;
end $$;

create or replace function _on_booking_events() returns trigger language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'INSERT' then
    update waitlist set status = 'prenotato' where student_id = new.student_id and date = new.date and hour = new.hour and status in ('attiva', 'avvisato');
    if new.source <> 'app' then
      perform _push(new.student_id, 'Lezione prenotata', format('%s · %s.', initcap(_when(new.date, new.hour, new.start_min)),
                    (select name from rooms where id = new.room_id)), '', 'lezione-' || new.id);
    end if;
  elsif old.status = 'confermata' and new.status = 'annullata' then
    perform _waitlist_freed(old.date, old.hour, old.teacher_id, old.student_id);
    if coalesce(new.cancelled_by, '') <> 'allievo' then
      perform _push(new.student_id, 'Lezione annullata', format('La lezione di %s è stata annullata.', _when(old.date, old.hour, old.start_min)), '', 'lezione-' || new.id);
    end if;
  elsif old.status = 'confermata' and new.status = 'confermata'
        and (old.date, old.hour, old.room_id, old.teacher_id) is distinct from (new.date, new.hour, new.room_id, new.teacher_id) then
    if (old.date, old.hour) is distinct from (new.date, new.hour) then
      perform _waitlist_freed(old.date, old.hour, old.teacher_id, old.student_id);
    end if;
    perform _push(new.student_id, 'Lezione spostata', format('Nuovo orario: %s · %s con %s.', _when(new.date, new.hour, new.start_min),
                  (select name from rooms where id = new.room_id), (select name from teachers where id = new.teacher_id)), '', 'lezione-' || new.id);
  end if;
  return new;
end $$;
create or replace trigger on_booking_events after insert or update on bookings for each row execute function _on_booking_events();

-- ------------------------------------------------------------ spostamento (nucleo comune a segreteria, app e assistente)
create or replace function _move_booking(p_id bigint, p_date date, p_hour int, p_room_id bigint, p_teacher_id bigint,
  p_by text, p_student bigint default null, p_force boolean default false) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  b bookings; v_room rooms; v_teacher teachers; v_tid bigint; v_blk blocks; v_con text; v_consent boolean; v_limit int := _setting_int('cancel_hours');
begin
  select * into b from bookings where id = p_id for update;
  if not found or b.status <> 'confermata' then perform _err('Lezione non trovata o già annullata.'); end if;
  if p_by <> 'segreteria' and b.student_id is distinct from p_student then perform _err('Lezione non trovata.'); end if;
  v_tid := coalesce(p_teacher_id, b.teacher_id);
  if b.date = p_date and b.hour = p_hour and b.room_id = p_room_id and b.teacher_id = v_tid then return _booking_json(p_id); end if;

  if p_date is null or p_hour is null then perform _err('Data o ora non valida.'); end if;
  if _slot_start(b.date, b.hour) <= now() then perform _err('La lezione è già iniziata o passata: non si può spostare.'); end if;
  if p_by <> 'segreteria' then
    if _slot_start(b.date, b.hour) - now() < make_interval(hours => v_limit) then
      perform _err(format('Si può spostare fino a %s ore prima. Per spostarla ora contatta la segreteria.', v_limit));
    end if;
    if p_date > _bookable_until() then perform _err(format('Si può prenotare al massimo %s giorni avanti.', _setting_int('horizon_days'))); end if;
  end if;
  if _slot_start(p_date, p_hour) <= now() then perform _err('Non si può spostare una lezione in un orario già passato.'); end if;
  if not (p_hour = any(_opening_hours(p_date))) then perform _err('La scuola è chiusa a quell''ora.'); end if;
  select * into v_room from rooms where id = p_room_id and active;
  if not found then perform _err('Sala non valida.'); end if;
  select * into v_teacher from teachers where id = v_tid and active;
  if not found then perform _err('Insegnante non valido.'); end if;

  select * into v_blk from blocks x where x.date = p_date and p_hour >= x.start_hour and p_hour < x.end_hour
     and (x.room_id = p_room_id or (x.room_id is null and x.teacher_id is null)) limit 1;
  if found then perform _err(format('%s non è disponibile a quell''ora (%s).', v_room.name, v_blk.title)); end if;
  if exists (select 1 from blocks x where x.date = p_date and x.teacher_id = v_tid and p_hour >= x.start_hour and p_hour < x.end_hour) then
    perform _err(format('%s non è disponibile a quell''ora.', v_teacher.name));
  end if;
  if not (p_by = 'segreteria' and coalesce(p_force, false)) and not exists (select 1 from shifts s where s.teacher_id = v_tid
       and s.weekday = extract(dow from p_date)::int and p_hour >= s.start_hour and p_hour < s.end_hour) then
    perform _err(format('%s non è in turno a quell''ora.', v_teacher.name));
  end if;

  begin
    update bookings set date = p_date, hour = p_hour, room_id = p_room_id, teacher_id = v_tid, cal_stale = true,
           start_min = case when (date, hour) is distinct from (p_date, p_hour) then 0 else start_min end,
           reminded_at = case when (date, hour) is distinct from (p_date, p_hour) then null else reminded_at end,
           student_confirmed_at = case when (date, hour) is distinct from (p_date, p_hour) then null else student_confirmed_at end,
           teacher_confirmed_at = case when (date, hour, teacher_id) is distinct from (p_date, p_hour, v_tid) then null else teacher_confirmed_at end,
           room_confirmed_at = null
     where id = p_id;
  exception when unique_violation then
    get stacked diagnostics v_con = constraint_name;
    if v_con = 'uq_room_slot' then perform _err(format('%s è già occupata a quell''ora.', v_room.name));
    elsif v_con = 'uq_teacher_slot' then perform _err(format('%s ha già una lezione a quell''ora.', v_teacher.name));
    elsif v_con = 'uq_student_slot' then perform _err('C''è già un''altra lezione a quell''ora.');
    else raise; end if;
  end;

  insert into outbox(kind, booking_id) values ('cal_sync', p_id);
  select wa_consent into v_consent from students where id = b.student_id;
  if v_consent and p_by <> 'whatsapp' then insert into outbox(kind, booking_id) values ('wa_confirm', p_id); end if;
  perform _kick_worker();
  return _booking_json(p_id);
end $$;

