-- ------------------------------------------------------------ conferme
create or replace function confirm_my_booking(p_id bigint) returns jsonb language plpgsql security definer set search_path = public as $$
declare s students := _current_student();
begin
  update bookings set student_confirmed_at = coalesce(student_confirmed_at, now())
   where id = p_id and student_id = s.id and status = 'confermata' and _slot_start(date, hour) > now();
  if not found then perform _err('Lezione non trovata.'); end if;
  return jsonb_build_object('ok', true);
end $$;

create or replace function teacher_confirm(p_id bigint, p_value boolean default true) returns jsonb language plpgsql security definer set search_path = public as $$
declare v_tid bigint := _teacher_of_user();
begin
  if v_tid is null and not is_staff() then perform _err('Accesso riservato agli insegnanti e alla segreteria.'); end if;
  update bookings set teacher_confirmed_at = case when p_value then coalesce(teacher_confirmed_at, now()) end
   where id = p_id and status = 'confermata' and (is_staff() or teacher_id = v_tid);
  if not found then perform _err('Lezione non trovata.'); end if;
  return jsonb_build_object('ok', true);
end $$;

create or replace function admin_confirm(p_id bigint, p_what text, p_value boolean default true) returns jsonb language plpgsql security definer set search_path = public as $$
begin
  perform _require_staff();
  if p_what = 'sala' then update bookings set room_confirmed_at = case when p_value then coalesce(room_confirmed_at, now()) end where id = p_id;
  elsif p_what = 'insegnante' then update bookings set teacher_confirmed_at = case when p_value then coalesce(teacher_confirmed_at, now()) end where id = p_id;
  elsif p_what = 'allievo' then update bookings set student_confirmed_at = case when p_value then coalesce(student_confirmed_at, now()) end where id = p_id;
  else perform _err('Conferma non valida.'); end if;
  return jsonb_build_object('ok', true);
end $$;

create or replace function admin_set_attendance(p_id bigint, p_value text) returns jsonb language plpgsql security definer set search_path = public as $$
begin
  perform _require_staff();
  if p_value is not null and p_value not in ('presente', 'assente') then perform _err('Valore non valido.'); end if;
  update bookings set attendance = p_value where id = p_id and status = 'confermata' and _slot_start(date, hour) <= now();
  if not found then perform _err('Si può segnare la presenza solo per lezioni iniziate o passate.'); end if;
  return jsonb_build_object('ok', true);
end $$;

-- ------------------------------------------------------------ lista d'attesa
create or replace function _waitlist_add(p_student bigint, p_date date, p_hour int, p_teacher bigint, p_source text, p_note text default '')
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_id bigint; v_teacher text;
begin
  if p_date is null or p_hour is null then perform _err('Data o ora non valida.'); end if;
  if _slot_start(p_date, p_hour) <= now() then perform _err('Quest''ora è già passata.'); end if;
  if not (p_hour = any(_opening_hours(p_date))) then perform _err('La scuola è chiusa a quell''ora.'); end if;
  if exists (select 1 from bookings where student_id = p_student and date = p_date and hour = p_hour and status = 'confermata') then
    perform _err('Hai già una lezione a quell''ora.');
  end if;
  if p_teacher is not null then select name into v_teacher from teachers where id = p_teacher and active;
    if v_teacher is null then perform _err('Insegnante non valido.'); end if;
  end if;
  begin
    insert into waitlist(student_id, date, hour, teacher_id, source, note) values (p_student, p_date, p_hour, p_teacher, p_source, left(coalesce(p_note, ''), 200))
    returning id into v_id;
  exception when unique_violation then perform _err('Sei già in lista d''attesa per quell''ora.');
  end;
  insert into msg_outbox(kind, student_id, params)
    select 'wl_ack', p_student, jsonb_build_object('date', p_date, 'hour', p_hour, 'teacher', v_teacher, 'waitlist_id', v_id)
    from students where id = p_student and wa_consent;
  perform _kick_worker();
  return jsonb_build_object('id', v_id, 'date', p_date, 'hour', p_hour, 'teacher', v_teacher, 'status', 'attiva');
end $$;

create or replace function _waitlist_json(p_where_student bigint, p_from date, p_to date) returns jsonb language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(jsonb_build_object('id', w.id, 'date', w.date, 'hour', w.hour, 'teacher_id', w.teacher_id, 'teacher', t.name,
      'status', w.status, 'source', w.source, 'note', w.note, 'created_at', w.created_at, 'notified_at', w.notified_at,
      'student_id', s.id, 'student_name', s.name, 'student_phone', s.phone, 'wa_consent', s.wa_consent,
      'push', exists (select 1 from push_subs p where p.student_id = s.id and p.gone_at is null),
      'free_now', exists (select 1 from jsonb_array_elements(_day_grid(w.date)->'cells') c
                          where (c->>'hour')::int = w.hour and c->>'status' = 'free' and (w.teacher_id is null or c->'teachers' @> to_jsonb(w.teacher_id))))
    order by w.date, w.hour, w.created_at), '[]')
  from waitlist w join students s on s.id = w.student_id left join teachers t on t.id = w.teacher_id
  where (p_where_student is null or w.student_id = p_where_student) and w.date between p_from and p_to
    and (p_where_student is null or w.status in ('attiva', 'avvisato'))
$$;

