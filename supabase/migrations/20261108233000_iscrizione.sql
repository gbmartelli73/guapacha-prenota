-- Iscrizione dall'app (email/cellulare + password) e opzioni di accesso degli allievi.

alter table students add column if not exists guardian_name text not null default '';
alter table students add column if not exists privacy_at timestamptz;
alter table students add column if not exists signup_at timestamptz;

insert into settings(key, value) values ('login_otp', 'no'), ('signup_open', 'si') on conflict (key) do nothing;

create table if not exists signup_log (
  id bigint generated by default as identity primary key,
  ip_hash text not null, ok boolean not null default false, created_at timestamptz not null default now()
);
create index if not exists signup_log_time on signup_log(created_at);
alter table signup_log enable row level security;
revoke all on table signup_log from anon, authenticated;

-- cosa mostra la schermata di accesso dell'app (pubblico)
create or replace function auth_options() returns jsonb language sql stable security definer set search_path = public as $$
  select jsonb_build_object('otp', coalesce(_setting('login_otp'), 'no') = 'si', 'signup', coalesce(_setting('signup_open'), 'si') = 'si',
                            'school_phone', _setting('school_phone'), 'school', _setting('school_name'))
$$;

-- l'amministratore sceglie come entrano gli allievi
create or replace function sa_auth_options(p_otp boolean default null, p_signup boolean default null) returns jsonb
language plpgsql security definer set search_path = public as $$
begin
  perform _require_admin();
  if p_otp is not null then insert into settings values ('login_otp', case when p_otp then 'si' else 'no' end) on conflict (key) do update set value = excluded.value; end if;
  if p_signup is not null then insert into settings values ('signup_open', case when p_signup then 'si' else 'no' end) on conflict (key) do update set value = excluded.value; end if;
  return auth_options();
end $$;

-- ------------------------------------------------------------ usate solo dalla Edge Function "iscrizione" (service_role)
-- limiti anti-abuso: 5 tentativi l'ora per indirizzo, 60 l'ora in totale
create or replace function access_signup_allowed(p_ip_hash text) returns boolean language plpgsql security definer set search_path = public as $$
begin
  delete from signup_log where created_at < now() - interval '2 days';
  if (select count(*) from signup_log where ip_hash = p_ip_hash and created_at > now() - interval '1 hour') >= 5 then return false; end if;
  if (select count(*) from signup_log where created_at > now() - interval '1 hour') >= 60 then return false; end if;
  insert into signup_log(ip_hash) values (p_ip_hash);
  return true;
end $$;

-- controlli prima di creare l'account: dati validi, numero ed email non già usati
create or replace function access_signup_check(p_data jsonb) returns jsonb language plpgsql stable security definer set search_path = public as $$
declare v_phone text := _norm_phone(p_data->>'phone'); v_birth date; v_email text := lower(trim(coalesce(p_data->>'email', '')));
begin
  if coalesce(_setting('signup_open'), 'si') <> 'si' then perform _err('Le iscrizioni dall''app sono chiuse: rivolgiti alla segreteria.'); end if;
  if length(trim(coalesce(p_data->>'first_name', ''))) < 2 or length(trim(coalesce(p_data->>'last_name', ''))) < 2 then perform _err('Scrivi nome e cognome.'); end if;
  if v_email !~ '^[^@\s]+@[^@\s]+\.[a-z]{2,}$' then perform _err('Email non valida.'); end if;
  begin v_birth := nullif(p_data->>'birth_date', '')::date; exception when others then perform _err('Data di nascita non valida.'); end;
  if v_birth is null then perform _err('Inserisci la data di nascita.'); end if;
  if v_birth > _today() or v_birth < date '1900-01-01' then perform _err('Data di nascita non valida.'); end if;
  if age(_today(), v_birth) < interval '18 years' and length(trim(coalesce(p_data->>'guardian_name', ''))) < 3 then
    perform _err('Per un allievo minorenne serve il nome del genitore o tutore.');
  end if;
  if nullif(trim(coalesce(p_data->>'tax_code', '')), '') is not null
     and upper(regexp_replace(p_data->>'tax_code', '\s', '', 'g')) !~ '^[A-Z]{6}[0-9LMNPQRSTUV]{2}[A-Z][0-9LMNPQRSTUV]{2}[A-Z][0-9LMNPQRSTUV]{3}[A-Z]$' then
    perform _err('Codice fiscale non valido.');
  end if;
  if coalesce((p_data->>'privacy')::boolean, false) is not true then perform _err('Per iscriverti devi accettare l''informativa sulla privacy.'); end if;
  if exists (select 1 from students where phone = v_phone) or exists (select 1 from auth.users where phone = v_phone) then
    perform _err('Questo numero è già registrato. Se sei già allievo chiedi alla segreteria le tue credenziali.');
  end if;
  if exists (select 1 from auth.users where lower(email) = v_email) then perform _err('Questa email è già registrata: accedi con la tua password.'); end if;
  return jsonb_build_object('phone', v_phone, 'email', v_email);
end $$;

create or replace function access_signup(p_user uuid, p_data jsonb) returns jsonb language plpgsql security definer set search_path = public as $$
declare v_phone text := _norm_phone(p_data->>'phone'); v_id bigint;
begin
  insert into students(user_id, phone) values (p_user, v_phone) on conflict (phone) do nothing;
  update students set
      user_id = p_user,
      name = left(initcap(trim(p_data->>'first_name')) || ' ' || initcap(trim(p_data->>'last_name')), 80),
      email = lower(trim(p_data->>'email')),
      birth_date = nullif(p_data->>'birth_date', '')::date,
      tax_code = upper(left(regexp_replace(coalesce(p_data->>'tax_code', ''), '\s', '', 'g'), 16)),
      address = left(trim(coalesce(p_data->>'address', '')), 200),
      guardian_name = left(trim(coalesce(p_data->>'guardian_name', '')), 80),
      wa_consent = coalesce((p_data->>'wa_consent')::boolean, false),
      privacy_at = now(), signup_at = now()
   where phone = v_phone and (user_id is null or user_id = p_user)
   returning id into v_id;
  if v_id is null then perform _err('Questo numero è già registrato.'); end if;
  update signup_log set ok = true where id = (select max(id) from signup_log);
  return jsonb_build_object('ok', true, 'student_id', v_id);
end $$;

-- scheda allievo in segreteria: anche genitore/tutore e data di iscrizione dall'app
create or replace function admin_student(p_id bigint) returns jsonb language plpgsql stable security definer set search_path = public as $$
declare s students;
begin
  perform _require_staff();
  select * into s from students where id = p_id;
  if not found then perform _err('Allievo non trovato.'); end if;
  return _card(s) || jsonb_build_object('id', s.id, 'notes', s.notes, 'wa_consent', s.wa_consent, 'has_app', s.user_id is not null,
    'created_at', s.created_at, 'push', exists (select 1 from push_subs p where p.student_id = s.id and p.gone_at is null),
    'upcoming', coalesce((select jsonb_agg(jsonb_build_object('id', b.id, 'date', b.date, 'hour', b.hour, 'start_min', b.start_min,
        'room', r.name, 'teacher', t.name, 'student_confirmed', b.student_confirmed_at is not null) order by b.date, b.hour)
        from bookings b join rooms r on r.id = b.room_id join teachers t on t.id = b.teacher_id
        where b.student_id = s.id and b.status = 'confermata' and _slot_start(b.date, b.hour) > now()), '[]'),
    'stats', jsonb_build_object(
        'cancelled', (select count(*) from bookings where student_id = s.id and status = 'annullata'),
        'absent', (select count(*) from bookings where student_id = s.id and status = 'confermata' and attendance = 'assente')),
    'ledger', coalesce((select jsonb_agg(jsonb_build_object('id', id, 'delta', delta, 'reason', reason, 'note', note, 'created_at', created_at)
        order by created_at desc) from points_ledger where student_id = s.id), '[]'),
    'waitlist', _waitlist_json(s.id, _today(), _today() + 120),
    'guardian_name', s.guardian_name, 'signup_at', s.signup_at, 'privacy_at', s.privacy_at);
end $$;

revoke execute on function access_signup_allowed(text), access_signup_check(jsonb), access_signup(uuid, jsonb) from public, anon, authenticated;
grant execute on function access_signup_allowed(text), access_signup_check(jsonb), access_signup(uuid, jsonb) to service_role;
revoke execute on function auth_options(), sa_auth_options(boolean, boolean) from public;
grant execute on function auth_options() to anon, authenticated;
revoke execute on function sa_auth_options(boolean, boolean) from anon;
grant execute on function sa_auth_options(boolean, boolean) to authenticated;
