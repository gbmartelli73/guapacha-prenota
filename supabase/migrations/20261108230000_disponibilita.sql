-- Disponibilità degli insegnanti: turni settimanali, assenze (date bloccate) e disponibilità extra in date precise.
-- Le gestiscono l'insegnante stesso (solo le sue) e la segreteria (tutti).

create table if not exists extra_hours (
  id bigint generated by default as identity primary key,
  teacher_id bigint not null references teachers(id) on delete cascade,
  date date not null,
  start_hour int not null check (start_hour between 0 and 23),
  end_hour int not null check (end_hour between 1 and 24 and end_hour > start_hour),
  note text not null default '',
  created_by uuid default auth.uid(),
  created_at timestamptz not null default now()
);
create index if not exists extra_hours_date on extra_hours(date, teacher_id);
alter table extra_hours enable row level security;
revoke all on table extra_hours from anon, authenticated;

alter table blocks add column if not exists created_by uuid default auth.uid();
alter table blocks add column if not exists created_at timestamptz not null default now();

-- l'insegnante è disponibile a quell'ora: turno settimanale oppure disponibilità extra in quella data (le assenze si controllano a parte)
create or replace function _teacher_on(p_teacher bigint, p_date date, p_hour int) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from shifts s where s.teacher_id = p_teacher and s.weekday = extract(dow from p_date)::int
                  and p_hour >= s.start_hour and p_hour < s.end_hour)
      or exists (select 1 from extra_hours e where e.teacher_id = p_teacher and e.date = p_date
                  and p_hour >= e.start_hour and p_hour < e.end_hour)
$$;
create or replace function _day_grid(p_date date, p_student bigint default null, p_admin boolean default false)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare
  v_hours int[] := _opening_hours(p_date);
  v_wd int := extract(dow from p_date)::int;
  v_beyond boolean := not p_admin and p_date > _bookable_until();
  v_cells jsonb := '[]';
  h int; r record; b record; blk record; v_avail bigint[]; v_cell jsonb;
begin
  foreach h in array v_hours loop
    select coalesce(array_agg(t.id order by t.id), '{}') into v_avail from teachers t
     where t.active
       and _teacher_on(t.id, p_date, h)
       and not exists (select 1 from bookings x where x.date = p_date and x.hour = h and x.teacher_id = t.id and x.status = 'confermata')
       and not exists (select 1 from blocks x where x.date = p_date and x.teacher_id = t.id and h >= x.start_hour and h < x.end_hour);
    for r in select id from rooms where active order by sort, id loop
      v_cell := jsonb_build_object('hour', h, 'room_id', r.id);
      select x.*, s.name as student_name, s.phone as student_phone into b
        from bookings x join students s on s.id = x.student_id
       where x.date = p_date and x.hour = h and x.room_id = r.id and x.status = 'confermata';
      if found then
        v_cell := v_cell || jsonb_build_object('status', 'booked', 'teacher_id', b.teacher_id);
        if p_admin then
          v_cell := v_cell || jsonb_build_object('booking_id', b.id, 'student_id', b.student_id, 'student_name', b.student_name,
            'student_phone', b.student_phone, 'note', b.note, 'source', b.source, 'sync_error', b.sync_error, 'created_at', b.created_at,
            'guests', b.guests, 'start_min', b.start_min, 'attendance', b.attendance,
            'room_confirmed', b.room_confirmed_at is not null, 'teacher_confirmed', b.teacher_confirmed_at is not null,
            'student_confirmed', b.student_confirmed_at is not null);
        elsif p_student is not null and b.student_id = p_student then
          v_cell := v_cell || jsonb_build_object('mine', true, 'booking_id', b.id, 'note', b.note, 'guests', b.guests, 'start_min', b.start_min);
        end if;
      else
        select * into blk from blocks x where x.date = p_date and h >= x.start_hour and h < x.end_hour
           and (x.room_id = r.id or (x.room_id is null and x.teacher_id is null)) order by x.id limit 1;
        if found then
          v_cell := v_cell || jsonb_build_object('status', 'blocked', 'title', blk.title);
          if p_admin then v_cell := v_cell || jsonb_build_object('block_id', blk.id); end if;
        elsif _slot_start(p_date, h) <= now() then
          v_cell := v_cell || jsonb_build_object('status', 'past');
        elsif cardinality(v_avail) = 0 or v_beyond then
          v_cell := v_cell || jsonb_build_object('status', 'off');
        else
          v_cell := v_cell || jsonb_build_object('status', 'free', 'teachers', to_jsonb(v_avail));
        end if;
      end if;
      v_cells := v_cells || jsonb_build_array(v_cell);
    end loop;
  end loop;
  return jsonb_build_object(
    'date', p_date, 'label', _fmt_date(p_date), 'hours', to_jsonb(v_hours), 'cells', v_cells, 'bookable_until', _bookable_until(),
    'rooms', coalesce((select jsonb_agg(jsonb_build_object('id', id, 'name', name, 'info', info) order by sort, id) from rooms where active), '[]'),
    'teachers', coalesce((select jsonb_agg(jsonb_build_object('id', id, 'name', name, 'style', style, 'color', color) order by id) from teachers where active), '[]'));
end $$;

create or replace function _create_booking(p_date date, p_hour int, p_room bigint, p_teacher bigint, p_student bigint,
  p_note text default '', p_source text default 'app', p_admin boolean default false, p_force boolean default false)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_room rooms; v_teacher teachers; v_blk blocks; v_id bigint; v_con text; v_active int; v_max int;
begin
  if p_date is null or p_hour is null then perform _err('Data o ora non valida.'); end if;
  if not (p_hour = any(_opening_hours(p_date))) then perform _err('La scuola è chiusa a quell''ora.'); end if;
  if _slot_start(p_date, p_hour) <= now() then perform _err('Quest''ora è già passata.'); end if;
  if not p_admin and p_date > _bookable_until() then
    perform _err(format('Si può prenotare al massimo %s giorni avanti.', _setting_int('horizon_days')));
  end if;
  select * into v_room from rooms where id = p_room and active;
  if not found then perform _err('Sala non valida.'); end if;
  select * into v_teacher from teachers where id = p_teacher and active;
  if not found then perform _err('Insegnante non valido.'); end if;
  if not exists (select 1 from students where id = p_student) then perform _err('Allievo non trovato.'); end if;

  select * into v_blk from blocks x where x.date = p_date and p_hour >= x.start_hour and p_hour < x.end_hour
     and (x.room_id = p_room or (x.room_id is null and x.teacher_id is null)) limit 1;
  if found then perform _err(format('%s non è disponibile a quell''ora (%s).', v_room.name, v_blk.title)); end if;
  if exists (select 1 from blocks x where x.date = p_date and x.teacher_id = p_teacher and p_hour >= x.start_hour and p_hour < x.end_hour) then
    perform _err(format('%s non è disponibile a quell''ora.', v_teacher.name));
  end if;
  if not _teacher_on(p_teacher, p_date, p_hour) and not (p_admin and p_force) then
    perform _err(format('%s non è in turno a quell''ora.', v_teacher.name));
  end if;

  if not p_admin then
    v_max := coalesce(nullif(_setting_int('max_active_per_student'), 0), 6);
    select count(*) into v_active from bookings
     where student_id = p_student and status = 'confermata' and _slot_start(date, hour) > now();
    if v_active >= v_max then perform _err(format('Hai già %s lezioni in programma: il massimo è %s.', v_active, v_max)); end if;
  end if;

  begin
    insert into bookings(date, hour, room_id, teacher_id, student_id, note, source)
    values (p_date, p_hour, p_room, p_teacher, p_student, left(coalesce(p_note, ''), 200), p_source)
    returning id into v_id;
  exception when unique_violation then
    get stacked diagnostics v_con = constraint_name;
    if v_con = 'uq_room_slot' then perform _err(format('%s è appena stata prenotata da qualcun altro. Scegli un''altra sala.', v_room.name));
    elsif v_con = 'uq_teacher_slot' then perform _err(format('%s è già impegnato a quell''ora. Scegli un altro insegnante.', v_teacher.name));
    elsif v_con = 'uq_student_slot' then perform _err('Hai già una lezione prenotata a quell''ora.');
    else raise; end if;
  end;
  return _booking_json(v_id);
end $$;

create or replace function _move_booking(p_id bigint, p_date date, p_hour int, p_room_id bigint, p_teacher_id bigint,
  p_by text, p_student bigint default null, p_force boolean default false) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  b bookings; v_room rooms; v_teacher teachers; v_tid bigint; v_blk blocks; v_con text; v_consent boolean; v_limit int := _setting_int('cancel_hours');
begin
  select * into b from bookings where id = p_id for update;
  if not found or b.status <> 'confermata' then perform _err('Lezione non trovata o già annullata.'); end if;
  if p_by <> 'segreteria' and b.student_id is distinct from p_student then perform _err('Lezione non trovata.'); end if;
  v_tid := coalesce(p_teacher_id, b.teacher_id);
  if b.date = p_date and b.hour = p_hour and b.room_id = p_room_id and b.teacher_id = v_tid then return _booking_json(p_id); end if;

  if p_date is null or p_hour is null then perform _err('Data o ora non valida.'); end if;
  if _slot_start(b.date, b.hour) <= now() then perform _err('La lezione è già iniziata o passata: non si può spostare.'); end if;
  if p_by <> 'segreteria' then
    if _slot_start(b.date, b.hour) - now() < make_interval(hours => v_limit) then
      perform _err(format('Si può spostare fino a %s ore prima. Per spostarla ora contatta la segreteria.', v_limit));
    end if;
    if p_date > _bookable_until() then perform _err(format('Si può prenotare al massimo %s giorni avanti.', _setting_int('horizon_days'))); end if;
  end if;
  if _slot_start(p_date, p_hour) <= now() then perform _err('Non si può spostare una lezione in un orario già passato.'); end if;
  if not (p_hour = any(_opening_hours(p_date))) then perform _err('La scuola è chiusa a quell''ora.'); end if;
  select * into v_room from rooms where id = p_room_id and active;
  if not found then perform _err('Sala non valida.'); end if;
  select * into v_teacher from teachers where id = v_tid and active;
  if not found then perform _err('Insegnante non valido.'); end if;

  select * into v_blk from blocks x where x.date = p_date and p_hour >= x.start_hour and p_hour < x.end_hour
     and (x.room_id = p_room_id or (x.room_id is null and x.teacher_id is null)) limit 1;
  if found then perform _err(format('%s non è disponibile a quell''ora (%s).', v_room.name, v_blk.title)); end if;
  if exists (select 1 from blocks x where x.date = p_date and x.teacher_id = v_tid and p_hour >= x.start_hour and p_hour < x.end_hour) then
    perform _err(format('%s non è disponibile a quell''ora.', v_teacher.name));
  end if;
  if not (p_by = 'segreteria' and coalesce(p_force, false)) and not _teacher_on(v_tid, p_date, p_hour) then
    perform _err(format('%s non è in turno a quell''ora.', v_teacher.name));
  end if;

  begin
    update bookings set date = p_date, hour = p_hour, room_id = p_room_id, teacher_id = v_tid, cal_stale = true,
           start_min = case when (date, hour) is distinct from (p_date, p_hour) then 0 else start_min end,
           reminded_at = case when (date, hour) is distinct from (p_date, p_hour) then null else reminded_at end,
           student_confirmed_at = case when (date, hour) is distinct from (p_date, p_hour) then null else student_confirmed_at end,
           teacher_confirmed_at = case when (date, hour, teacher_id) is distinct from (p_date, p_hour, v_tid) then null else teacher_confirmed_at end,
           room_confirmed_at = null
     where id = p_id;
  exception when unique_violation then
    get stacked diagnostics v_con = constraint_name;
    if v_con = 'uq_room_slot' then perform _err(format('%s è già occupata a quell''ora.', v_room.name));
    elsif v_con = 'uq_teacher_slot' then perform _err(format('%s ha già una lezione a quell''ora.', v_teacher.name));
    elsif v_con = 'uq_student_slot' then perform _err('C''è già un''altra lezione a quell''ora.');
    else raise; end if;
  end;

  insert into outbox(kind, booking_id) values ('cal_sync', p_id);
  select wa_consent into v_consent from students where id = b.student_id;
  if v_consent and p_by <> 'whatsapp' then insert into outbox(kind, booking_id) values ('wa_confirm', p_id); end if;
  perform _kick_worker();
  return _booking_json(p_id);
end $$;

create or replace function admin_occupancy(p_start date) returns jsonb language plpgsql stable security definer set search_path = public as $$
declare v_end date := p_start + 6;
begin
  perform _require_staff();
  return jsonb_build_object('start', p_start, 'end', v_end,
    'days', (select jsonb_agg(jsonb_build_object('date', d::date, 'label', _fmt_date(d::date), 'hours', cardinality(_opening_hours(d::date))) order by d)
             from generate_series(p_start, v_end, '1 day') d),
    'rooms', coalesce((select jsonb_agg(jsonb_build_object('id', r.id, 'name', r.name, 'days', (
        select jsonb_agg(jsonb_build_object('date', d::date,
          'open', (select count(*) from unnest(_opening_hours(d::date)) h
                   where not exists (select 1 from blocks x where x.date = d::date and h >= x.start_hour and h < x.end_hour
                                     and (x.room_id = r.id or (x.room_id is null and x.teacher_id is null)))),
          'booked', (select count(*) from bookings b where b.date = d::date and b.room_id = r.id and b.status = 'confermata'),
          'confirmed', (select count(*) from bookings b where b.date = d::date and b.room_id = r.id and b.status = 'confermata' and b.room_confirmed_at is not null))
          order by d) from generate_series(p_start, v_end, '1 day') d)) order by r.sort, r.id) from rooms r where r.active), '[]'),
    'teachers', coalesce((select jsonb_agg(jsonb_build_object('id', t.id, 'name', t.name, 'color', t.color, 'days', (
        select jsonb_agg(jsonb_build_object('date', d::date,
          'open', (select count(*) from unnest(_opening_hours(d::date)) h
                   where _teacher_on(t.id, d::date, h)
                     and not exists (select 1 from blocks x where x.date = d::date and x.teacher_id = t.id and h >= x.start_hour and h < x.end_hour)),
          'booked', (select count(*) from bookings b where b.date = d::date and b.teacher_id = t.id and b.status = 'confermata'),
          'confirmed', (select count(*) from bookings b where b.date = d::date and b.teacher_id = t.id and b.status = 'confermata' and b.teacher_confirmed_at is not null))
          order by d) from generate_series(p_start, v_end, '1 day') d)) order by t.id) from teachers t where t.active), '[]'),
    'lessons', coalesce((select jsonb_agg(jsonb_build_object('id', b.id, 'date', b.date, 'hour', b.hour, 'start_min', b.start_min,
        'room_id', b.room_id, 'room', r.name, 'teacher_id', b.teacher_id, 'teacher', t.name, 'student', s.name, 'guests', b.guests,
        'room_confirmed', b.room_confirmed_at is not null, 'teacher_confirmed', b.teacher_confirmed_at is not null,
        'student_confirmed', b.student_confirmed_at is not null, 'attendance', b.attendance,
        'past', _slot_start(b.date, b.hour) <= now()) order by b.date, b.hour, r.sort)
        from bookings b join rooms r on r.id = b.room_id join teachers t on t.id = b.teacher_id join students s on s.id = b.student_id
        where b.date between p_start and v_end and b.status = 'confermata'), '[]'),
    'waitlist', (select count(*) from waitlist where date between p_start and v_end and status = 'attiva'));
end $$;

-- ------------------------------------------------------------ API disponibilità (insegnante: solo sé stesso; segreteria: tutti)
create or replace function _avail_teacher(p_teacher_id bigint) returns bigint language plpgsql stable security definer set search_path = public as $$
declare v bigint;
begin
  if is_staff() then
    if p_teacher_id is null or not exists (select 1 from teachers where id = p_teacher_id) then perform _err('Scegli l''insegnante.'); end if;
    return p_teacher_id;
  end if;
  v := _require_teacher();
  if p_teacher_id is not null and p_teacher_id <> v then perform _err('Puoi modificare solo la tua disponibilità.'); end if;
  return v;
end $$;

create or replace function _who_name(p_uid uuid) returns text language sql stable security definer set search_path = public as $$
  select coalesce((select name from teachers where user_id = p_uid limit 1),
                  (select nullif(name, '') from staff where user_id = p_uid),
                  case when exists (select 1 from admins where user_id = p_uid) then 'Amministratore' end,
                  case when exists (select 1 from staff where user_id = p_uid) then 'Segreteria' end, '')
$$;

create or replace function avail_get(p_teacher_id bigint default null, p_days int default 90) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare v_tid bigint := _avail_teacher(case when p_teacher_id is null and is_staff()
                                              then (select id from teachers order by active desc, name limit 1) else p_teacher_id end);
  v_to date := _today() + least(greatest(coalesce(p_days, 90), 7), 400); t teachers;
begin
  select * into t from teachers where id = v_tid;
  return jsonb_build_object(
    'staff', is_staff(), 'today', _today(),
    'teacher', jsonb_build_object('id', t.id, 'name', t.name, 'style', t.style, 'color', t.color, 'active', t.active),
    'teachers', case when is_staff() then coalesce((select jsonb_agg(jsonb_build_object('id', id, 'name', name, 'style', style, 'active', active) order by active desc, name) from teachers), '[]') else '[]' end,
    'shifts', coalesce((select jsonb_agg(jsonb_build_object('weekday', weekday, 'start_hour', start_hour, 'end_hour', end_hour) order by weekday, start_hour) from shifts where teacher_id = v_tid), '[]'),
    'opening', coalesce((select jsonb_agg(to_jsonb(o) order by weekday) from opening o), '[]'),
    'blocks', coalesce((select jsonb_agg(jsonb_build_object('id', b.id, 'date', b.date, 'start_hour', b.start_hour, 'end_hour', b.end_hour, 'title', b.title,
        'by', _who_name(b.created_by), 'mine', b.created_by = auth.uid(), 'created_at', b.created_at,
        'lessons', (select count(*) from bookings x where x.teacher_id = v_tid and x.status = 'confermata' and x.date = b.date and x.hour >= b.start_hour and x.hour < b.end_hour))
      order by b.date, b.start_hour) from blocks b where b.teacher_id = v_tid and b.room_id is null and b.date between _today() and v_to), '[]'),
    'closures', coalesce((select jsonb_agg(jsonb_build_object('date', b.date, 'start_hour', b.start_hour, 'end_hour', b.end_hour, 'title', b.title) order by b.date, b.start_hour)
      from blocks b where b.room_id is null and b.teacher_id is null and b.date between _today() and v_to), '[]'),
    'extras', coalesce((select jsonb_agg(jsonb_build_object('id', e.id, 'date', e.date, 'start_hour', e.start_hour, 'end_hour', e.end_hour, 'note', e.note,
        'by', _who_name(e.created_by), 'created_at', e.created_at,
        'lessons', (select count(*) from bookings x where x.teacher_id = v_tid and x.status = 'confermata' and x.date = e.date and x.hour >= e.start_hour and x.hour < e.end_hour))
      order by e.date, e.start_hour) from extra_hours e where e.teacher_id = v_tid and e.date between _today() and v_to), '[]'),
    'upcoming', (select count(*) from bookings x where x.teacher_id = v_tid and x.status = 'confermata' and x.date >= _today()));
end $$;

-- lezioni future dell'insegnante che resterebbero fuori dai nuovi turni
create or replace function avail_save_shifts(p_teacher_id bigint, p_shifts jsonb, p_force boolean default false) returns jsonb
language plpgsql security definer set search_path = public as $$
declare v_tid bigint := _avail_teacher(p_teacher_id); sh jsonb; v_conf jsonb;
begin
  if jsonb_typeof(coalesce(p_shifts, '[]')) <> 'array' then perform _err('Turni non validi.'); end if;
  for sh in select * from jsonb_array_elements(coalesce(p_shifts, '[]')) loop
    if (sh->>'weekday')::int not between 0 and 6 or (sh->>'start_hour')::int not between 0 and 23
       or (sh->>'end_hour')::int > 24 or (sh->>'end_hour')::int <= (sh->>'start_hour')::int then
      perform _err('Turno non valido: l''ora di fine deve essere dopo l''inizio.');
    end if;
  end loop;
  select coalesce(jsonb_agg(jsonb_build_object('date', b.date, 'hour', b.hour, 'start_min', b.start_min, 'room', r.name) order by b.date, b.hour), '[]') into v_conf
    from bookings b join rooms r on r.id = b.room_id
   where b.teacher_id = v_tid and b.status = 'confermata' and _slot_start(b.date, b.hour) > now()
     and not exists (select 1 from jsonb_array_elements(coalesce(p_shifts, '[]')) x
                      where (x->>'weekday')::int = extract(dow from b.date)::int and b.hour >= (x->>'start_hour')::int and b.hour < (x->>'end_hour')::int)
     and not exists (select 1 from extra_hours e where e.teacher_id = v_tid and e.date = b.date and b.hour >= e.start_hour and b.hour < e.end_hour);
  if jsonb_array_length(v_conf) > 0 and not coalesce(p_force, false) then
    return jsonb_build_object('ok', false, 'conflicts', v_conf,
      'error', case when jsonb_array_length(v_conf) = 1 then '1 lezione già prenotata resta fuori dai nuovi turni. Resta valida: se non puoi farla, avvisa la segreteria.'
                    else jsonb_array_length(v_conf) || ' lezioni già prenotate restano fuori dai nuovi turni. Restano valide: se non puoi farle, avvisa la segreteria.' end);
  end if;
  delete from shifts where teacher_id = v_tid;
  insert into shifts(teacher_id, weekday, start_hour, end_hour)
    select v_tid, (x->>'weekday')::int, (x->>'start_hour')::int, (x->>'end_hour')::int from jsonb_array_elements(coalesce(p_shifts, '[]')) x;
  return jsonb_build_object('ok', true, 'kept', jsonb_array_length(v_conf));
end $$;

-- assenza: un giorno intero (0-24) o una fascia oraria, anche su più giorni
create or replace function avail_block(p_teacher_id bigint, p_date date, p_until date default null, p_start_hour int default 0, p_end_hour int default 24,
  p_title text default '', p_force boolean default false) returns jsonb
language plpgsql security definer set search_path = public as $$
declare v_tid bigint := _avail_teacher(p_teacher_id); v_until date := coalesce(p_until, p_date); v_conf jsonb; v_n int;
begin
  if p_date is null or v_until < p_date then perform _err('Controlla le date: la fine deve essere uguale o dopo l''inizio.'); end if;
  if p_date < _today() then perform _err('Non si possono bloccare date già passate.'); end if;
  if v_until - p_date > 120 then perform _err('Si possono bloccare al massimo 4 mesi alla volta.'); end if;
  if p_start_hour is null or p_end_hour is null or p_start_hour < 0 or p_end_hour > 24 or p_end_hour <= p_start_hour then perform _err('Orario non valido.'); end if;
  select coalesce(jsonb_agg(jsonb_build_object('id', b.id, 'date', b.date, 'hour', b.hour, 'start_min', b.start_min, 'room', r.name, 'student', s.name) order by b.date, b.hour), '[]') into v_conf
    from bookings b join rooms r on r.id = b.room_id join students s on s.id = b.student_id
   where b.teacher_id = v_tid and b.status = 'confermata' and b.date between p_date and v_until and b.hour >= p_start_hour and b.hour < p_end_hour;
  v_n := jsonb_array_length(v_conf);
  if v_n > 0 and not is_staff() then
    return jsonb_build_object('ok', false, 'conflicts', v_conf, 'error',
      format('In quel periodo hai %s già prenotat%s: chiedi alla segreteria di spostarl%s, poi potrai bloccare le date.',
        case when v_n = 1 then '1 lezione' else v_n || ' lezioni' end, case when v_n = 1 then 'a' else 'e' end, case when v_n = 1 then 'a' else 'e' end));
  end if;
  if v_n > 0 and not coalesce(p_force, false) then
    return jsonb_build_object('ok', false, 'conflicts', v_conf, 'can_force', true, 'error',
      case when v_n = 1 then 'In quel periodo c''è 1 lezione già prenotata con questo insegnante. Spostala o annullala, oppure blocca comunque (la lezione resta in agenda).'
           else format('In quel periodo ci sono %s lezioni già prenotate con questo insegnante. Spostale o annullale, oppure blocca comunque (le lezioni restano in agenda).', v_n) end);
  end if;
  insert into blocks(date, start_hour, end_hour, room_id, teacher_id, title, created_by)
    select d::date, p_start_hour, p_end_hour, null, v_tid, left(coalesce(nullif(trim(p_title), ''), 'Non disponibile'), 80), auth.uid()
      from generate_series(p_date, v_until, interval '1 day') d
     where not exists (select 1 from blocks x where x.teacher_id = v_tid and x.room_id is null and x.date = d::date and x.start_hour <= p_start_hour and x.end_hour >= p_end_hour);
  get diagnostics v_n = row_count;
  return jsonb_build_object('ok', true, 'created', v_n);
end $$;

create or replace function avail_unblock(p_id bigint) returns jsonb language plpgsql security definer set search_path = public as $$
declare b blocks;
begin
  select * into b from blocks where id = p_id and teacher_id is not null and room_id is null;
  if not found then perform _err('Assenza non trovata.'); end if;
  perform _avail_teacher(b.teacher_id);
  if b.date < _today() and not is_staff() then perform _err('Non si possono modificare le date passate.'); end if;
  delete from blocks where id = p_id;
  return jsonb_build_object('ok', true);
end $$;

create or replace function avail_extra_add(p_teacher_id bigint, p_date date, p_start_hour int, p_end_hour int, p_note text default '') returns jsonb
language plpgsql security definer set search_path = public as $$
declare v_tid bigint := _avail_teacher(p_teacher_id); v_open int[];
begin
  if p_date is null or p_date < _today() then perform _err('Scegli una data da oggi in poi.'); end if;
  if p_date > _today() + 400 then perform _err('Data troppo lontana.'); end if;
  if p_start_hour is null or p_end_hour is null or p_start_hour < 0 or p_end_hour > 24 or p_end_hour <= p_start_hour then perform _err('Orario non valido.'); end if;
  v_open := _opening_hours(p_date);
  if not exists (select 1 from unnest(v_open) h where h >= p_start_hour and h < p_end_hour) then
    perform _err(case when cardinality(v_open) = 0 then 'Quel giorno la scuola è chiusa.' else format('Quel giorno la scuola è aperta dalle %s alle %s.', lpad(v_open[1]::text, 2, '0') || ':00', lpad((v_open[cardinality(v_open)] + 1)::text, 2, '0') || ':00') end);
  end if;
  if exists (select 1 from extra_hours where teacher_id = v_tid and date = p_date and start_hour < p_end_hour and end_hour > p_start_hour) then
    perform _err('C''è già una disponibilità extra che si sovrappone in quella data.');
  end if;
  insert into extra_hours(teacher_id, date, start_hour, end_hour, note, created_by) values (v_tid, p_date, p_start_hour, p_end_hour, left(trim(coalesce(p_note, '')), 120), auth.uid());
  -- se c'era un'assenza che copre esattamente quella fascia, la disponibilità vince: la si toglie
  delete from blocks where teacher_id = v_tid and room_id is null and date = p_date and start_hour >= p_start_hour and end_hour <= p_end_hour;
  return jsonb_build_object('ok', true);
end $$;

create or replace function avail_extra_delete(p_id bigint) returns jsonb language plpgsql security definer set search_path = public as $$
declare e extra_hours;
begin
  select * into e from extra_hours where id = p_id;
  if not found then perform _err('Disponibilità non trovata.'); end if;
  perform _avail_teacher(e.teacher_id);
  delete from extra_hours where id = p_id;
  return jsonb_build_object('ok', true);
end $$;

-- per la segreteria: cosa hanno cambiato gli insegnanti negli ultimi giorni
create or replace function admin_avail_changes(p_days int default 14) returns jsonb language plpgsql stable security definer set search_path = public as $$
begin
  perform _require_staff();
  return coalesce((select jsonb_agg(x order by x->>'created_at' desc) from (
    select jsonb_build_object('kind', 'assenza', 'teacher', t.name, 'teacher_id', t.id, 'date', b.date, 'start_hour', b.start_hour, 'end_hour', b.end_hour,
           'note', b.title, 'by', _who_name(b.created_by), 'created_at', b.created_at,
           'lessons', (select count(*) from bookings x where x.teacher_id = t.id and x.status = 'confermata' and x.date = b.date and x.hour >= b.start_hour and x.hour < b.end_hour)) x
      from blocks b join teachers t on t.id = b.teacher_id
     where b.room_id is null and b.created_at > now() - make_interval(days => p_days) and b.date >= _today()
       and b.created_by in (select user_id from teachers where user_id is not null)
    union all
    select jsonb_build_object('kind', 'extra', 'teacher', t.name, 'teacher_id', t.id, 'date', e.date, 'start_hour', e.start_hour, 'end_hour', e.end_hour,
           'note', e.note, 'by', _who_name(e.created_by), 'created_at', e.created_at, 'lessons', 0)
      from extra_hours e join teachers t on t.id = e.teacher_id
     where e.created_at > now() - make_interval(days => p_days) and e.date >= _today()
       and e.created_by in (select user_id from teachers where user_id is not null)) q), '[]');
end $$;

