create or replace function admin_save_teacher(p_id bigint, p_name text, p_style text default '', p_color text default '#6F5FCB',
  p_phone text default '', p_active boolean default true, p_shifts jsonb default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_id bigint := p_id; sh jsonb;
begin
  perform _require_staff();
  if length(trim(coalesce(p_name, ''))) = 0 then perform _err('Inserisci il nome dell''insegnante.'); end if;
  if coalesce(p_color, '') !~* '^#[0-9a-f]{6}$' then p_color := '#6F5FCB'; end if;
  if v_id is null then
    insert into teachers(name, style, color, phone, active) values (trim(p_name), coalesce(p_style, ''), p_color, coalesce(p_phone, ''), coalesce(p_active, true)) returning id into v_id;
