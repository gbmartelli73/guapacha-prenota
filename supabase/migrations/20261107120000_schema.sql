create or replace function admin_create_block(p_date date, p_start_hour int, p_end_hour int, p_title text default 'Non disponibile',
  p_until date default null, p_weekly boolean default false, p_room_id bigint default null, p_teacher_id bigint default null, p_force boolean default false)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_until date := coalesce(p_until, p_date); d date; v_dates date[] := '{}'; v_conf jsonb;
begin
  perform _require_staff();
  if p_date is null or v_until < p_date then perform _err('Date non valide.'); end if;
  if p_start_hour is null or p_end_hour is null or p_start_hour < 0 or p_end_hour > 24 or p_end_hour <= p_start_hour then perform _err('Orario non valido.'); end if;
  d := p_date;
  while d <= v_until and cardinality(v_dates) < 120 loop
    v_dates := v_dates || d;
    d := d + case when p_weekly then 7 else 1 end;
  end loop;
  select coalesce(jsonb_agg(jsonb_build_object('id', b.id, 'date', b.date, 'hour', b.hour, 'room', r.name, 'student', s.name) order by b.date, b.hour), '[]')
    into v_conf
    from bookings b join rooms r on r.id = b.room_id join students s on s.id = b.student_id
   where b.status = 'confermata' and b.date = any(v_dates) and b.hour >= p_start_hour and b.hour < p_end_hour
     and ((p_room_id is null and p_teacher_id is null) or b.room_id = p_room_id or b.teacher_id = p_teacher_id);
  if jsonb_array_length(v_conf) > 0 and not coalesce(p_force, false) then
    return jsonb_build_object('ok', false, 'conflicts', v_conf,
      'error', case when jsonb_array_length(v_conf) = 1 then 'Nel periodo c''è 1 lezione già prenotata. Annullala prima o conferma comunque.'
                    else format('Nel periodo ci sono %s lezioni già prenotate. Annullale prima o conferma comunque.', jsonb_array_length(v_conf)) end);
  end if;
  insert into blocks(date, start_hour, end_hour, room_id, teacher_id, title)
    select x, p_start_hour, p_end_hour, p_room_id, p_teacher_id, left(coalesce(nullif(trim(p_title), ''), 'Non disponibile'), 80) from unnest(v_dates) x;
  return jsonb_build_object('ok', true, 'created', cardinality(v_dates));
end $$;

