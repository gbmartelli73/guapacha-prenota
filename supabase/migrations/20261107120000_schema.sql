-- ================================================================ helper
create or replace function _err(msg text) returns void language plpgsql as $$
begin raise exception using errcode = 'P0001', message = msg; end $$;

create or replace function _setting(k text) returns text language sql stable security definer set search_path = public as
$$ select value from settings where key = k $$;
create or replace function _setting_int(k text) returns int language sql stable security definer set search_path = public as
$$ select coalesce(nullif(value, '')::int, 0) from settings where key = k $$;
create or replace function _tz() returns text language sql stable security definer set search_path = public as
$$ select coalesce(nullif(_setting('timezone'), ''), 'Europe/Rome') $$;
create or replace function _today() returns date language sql stable security definer set search_path = public as
$$ select (now() at time zone _tz())::date $$;
create or replace function _slot_start(d date, h int) returns timestamptz language sql stable security definer set search_path = public as
$$ select (d + make_interval(hours => h)) at time zone _tz() $$;
create or replace function _bookable_until() returns date language sql stable security definer set search_path = public as
$$ select _today() + greatest(_setting_int('horizon_days'), 0) $$;

create or replace function _fmt_date(d date) returns text language sql immutable as $$
  select (array['domenica','lunedì','martedì','mercoledì','giovedì','venerdì','sabato'])[extract(dow from d)::int + 1]
      || ' ' || extract(day from d)::int || ' ' ||
         (array['gennaio','febbraio','marzo','aprile','maggio','giugno','luglio','agosto','settembre','ottobre','novembre','dicembre'])[extract(month from d)::int]
$$;
create or replace function _fmt_hour(h int) returns text language sql immutable as $$ select lpad(h::text, 2, '0') || ':00' $$;

-- 3331234567 → 393331234567 ; +39 333… → 393331234567
create or replace function _norm_phone(raw text) returns text language plpgsql immutable as $$
declare p text := regexp_replace(coalesce(raw, ''), '[^0-9+]', '', 'g');
begin
  if p like '+%' then p := substr(p, 2);
  elsif p like '00%' then p := substr(p, 3);
  elsif p ~ '^3[0-9]{8,9}$' or p ~ '^0[0-9]{5,10}$' then p := '39' || p;
  end if;
  if p !~ '^[0-9]{8,15}$' then perform _err('Numero di telefono non valido. Scrivilo con il prefisso, es. +39 333 1234567.'); end if;
  return p;
end $$;

create or replace function _opening_hours(d date) returns int[] language sql stable security definer set search_path = public as $$
  select coalesce((select array_agg(h order by h) from opening o, generate_series(o.start_hour, o.end_hour - 1) h
                   where o.weekday = extract(dow from d)::int and o.start_hour is not null), '{}')
$$;

create or replace function is_staff() returns boolean language sql stable security definer set search_path = public as
$$ select exists (select 1 from staff where user_id = auth.uid()) $$;

create or replace function _require_staff() returns void language plpgsql stable security definer set search_path = public as $$
begin if not is_staff() then perform _err('Accesso riservato alla segreteria.'); end if; end $$;

create or replace function _current_student() returns students language plpgsql security definer set search_path = public as $$
declare s students; u record;
begin
  if auth.uid() is null then perform _err('Accedi per continuare.'); end if;
  select * into s from students where user_id = auth.uid();
  if found then return s; end if;
  -- primo accesso: collega l'utente al suo numero (anche se la segreteria lo aveva già inserito)
  select id, phone into u from auth.users where id = auth.uid();
  if u.phone is null or u.phone = '' then perform _err('Accedi con il numero di telefono.'); end if;
  insert into students(user_id, phone) values (auth.uid(), _norm_phone(u.phone))
    on conflict (phone) do update set user_id = excluded.user_id
    returning * into s;
  return s;
end $$;

-- collega automaticamente i nuovi utenti con telefono a un allievo
create or replace function _on_auth_user() returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.phone is not null and new.phone <> '' then
    insert into public.students(user_id, phone) values (new.id, public._norm_phone(new.phone))
      on conflict (phone) do update set user_id = excluded.user_id;
  end if;
  return new;
exception when others then return new;  -- non bloccare mai l'accesso
end $$;
create or replace trigger on_auth_user_phone after insert or update of phone on auth.users
  for each row execute function _on_auth_user();

