-- Griglia di un giorno. p_student: chi guarda (vede "tua"); p_admin: vede nomi e telefoni.
create or replace function _day_grid(p_date date, p_student bigint default null, p_admin boolean default false)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare
  v_hours int[] := _opening_hours(p_date);
  v_wd int := extract(dow from p_date)::int;
  v_beyond boolean := not p_admin and p_date > _bookable_until();
  v_cells jsonb := '[]';
  h int; r record; b record; blk record; v_avail bigint[]; v_cell jsonb;
begin
  foreach h in array v_hours loop
    select coalesce(array_agg(t.id order by t.id), '{}') into v_avail from teachers t
     where t.active
       and exists (select 1 from shifts s where s.teacher_id = t.id and s.weekday = v_wd and h >= s.start_hour and h < s.end_hour)
       and not exists (select 1 from bookings x where x.date = p_date and x.hour = h and x.teacher_id = t.id and x.status = 'confermata')
       and not exists (select 1 from blocks x where x.date = p_date and x.teacher_id = t.id and h >= x.start_hour and h < x.end_hour);
    for r in select id from rooms where active order by sort, id loop
      v_cell := jsonb_build_object('hour', h, 'room_id', r.id);
      select x.*, s.name as student_name, s.phone as student_phone into b
        from bookings x join students s on s.id = x.student_id
       where x.date = p_date and x.hour = h and x.room_id = r.id and x.status = 'confermata';
      if found then
        v_cell := v_cell || jsonb_build_object('status', 'booked', 'teacher_id', b.teacher_id);
        if p_admin then
          v_cell := v_cell || jsonb_build_object('booking_id', b.id, 'student_id', b.student_id, 'student_name', b.student_name,
            'student_phone', b.student_phone, 'note', b.note, 'source', b.source, 'sync_error', b.sync_error, 'created_at', b.created_at);
        elsif p_student is not null and b.student_id = p_student then
          v_cell := v_cell || jsonb_build_object('mine', true, 'booking_id', b.id, 'note', b.note);
        end if;
      else
        select * into blk from blocks x where x.date = p_date and h >= x.start_hour and h < x.end_hour
           and (x.room_id = r.id or (x.room_id is null and x.teacher_id is null)) order by x.id limit 1;
        if found then
          v_cell := v_cell || jsonb_build_object('status', 'blocked', 'title', blk.title);
          if p_admin then v_cell := v_cell || jsonb_build_object('block_id', blk.id); end if;
        elsif _slot_start(p_date, h) <= now() then
          v_cell := v_cell || jsonb_build_object('status', 'past');
        elsif cardinality(v_avail) = 0 or v_beyond then
          v_cell := v_cell || jsonb_build_object('status', 'off');
        else
          v_cell := v_cell || jsonb_build_object('status', 'free', 'teachers', to_jsonb(v_avail));
        end if;
      end if;
      v_cells := v_cells || jsonb_build_array(v_cell);
    end loop;
  end loop;
  return jsonb_build_object(
    'date', p_date, 'label', _fmt_date(p_date), 'hours', to_jsonb(v_hours), 'cells', v_cells, 'bookable_until', _bookable_until(),
    'rooms', coalesce((select jsonb_agg(jsonb_build_object('id', id, 'name', name, 'info', info) order by sort, id) from rooms where active), '[]'),
    'teachers', coalesce((select jsonb_agg(jsonb_build_object('id', id, 'name', name, 'style', style, 'color', color) order by id) from teachers where active), '[]'));
end $$;

-- ore libere per giorno, per la striscia della settimana
create or replace function _week_summary(p_start date) returns jsonb language plpgsql stable security definer set search_path = public as $$
declare d date; v jsonb := '[]'; g jsonb; v_free int; h int;
begin
  for i in 0..6 loop
    d := p_start + i; v_free := 0;
    if cardinality(_opening_hours(d)) > 0 and d <= _bookable_until() and d >= _today() then
      g := _day_grid(d);
      for h in select (jsonb_array_elements_text(g->'hours'))::int loop
        v_free := v_free + least(
          (select count(*) from jsonb_array_elements(g->'cells') c where (c->>'hour')::int = h and c->>'status' = 'free'),
          coalesce((select jsonb_array_length(c->'teachers') from jsonb_array_elements(g->'cells') c
                     where (c->>'hour')::int = h and c->>'status' = 'free' limit 1), 0));
      end loop;
    end if;
    v := v || jsonb_build_array(jsonb_build_object('date', d, 'open', cardinality(_opening_hours(d)) > 0, 'free', v_free,
      'booked', (select count(*) from bookings where date = d and status = 'confermata')));
  end loop;
  return v;
end $$;

-- ============================================================ prenotazione
create or replace function _create_booking(p_date date, p_hour int, p_room bigint, p_teacher bigint, p_student bigint,
  p_note text default '', p_source text default 'app', p_admin boolean default false, p_force boolean default false)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_room rooms; v_teacher teachers; v_blk blocks; v_id bigint; v_con text; v_active int; v_max int;
begin
  if p_date is null or p_hour is null then perform _err('Data o ora non valida.'); end if;
  if not (p_hour = any(_opening_hours(p_date))) then perform _err('La scuola è chiusa a quell''ora.'); end if;
  if _slot_start(p_date, p_hour) <= now() then perform _err('Quest''ora è già passata.'); end if;
  if not p_admin and p_date > _bookable_until() then
    perform _err(format('Si può prenotare al massimo %s giorni avanti.', _setting_int('horizon_days')));
  end if;
  select * into v_room from rooms where id = p_room and active;
  if not found then perform _err('Sala non valida.'); end if;
  select * into v_teacher from teachers where id = p_teacher and active;
  if not found then perform _err('Insegnante non valido.'); end if;
  if not exists (select 1 from students where id = p_student) then perform _err('Allievo non trovato.'); end if;

  select * into v_blk from blocks x where x.date = p_date and p_hour >= x.start_hour and p_hour < x.end_hour
     and (x.room_id = p_room or (x.room_id is null and x.teacher_id is null)) limit 1;
  if found then perform _err(format('%s non è disponibile a quell''ora (%s).', v_room.name, v_blk.title)); end if;
  if exists (select 1 from blocks x where x.date = p_date and x.teacher_id = p_teacher and p_hour >= x.start_hour and p_hour < x.end_hour) then
    perform _err(format('%s non è disponibile a quell''ora.', v_teacher.name));
  end if;
  if not exists (select 1 from shifts s where s.teacher_id = p_teacher and s.weekday = extract(dow from p_date)::int
                  and p_hour >= s.start_hour and p_hour < s.end_hour) and not (p_admin and p_force) then
    perform _err(format('%s non è in turno a quell''ora.', v_teacher.name));
  end if;

  if not p_admin then
    v_max := coalesce(nullif(_setting_int('max_active_per_student'), 0), 6);
    select count(*) into v_active from bookings
     where student_id = p_student and status = 'confermata' and _slot_start(date, hour) > now();
    if v_active >= v_max then perform _err(format('Hai già %s lezioni in programma: il massimo è %s.', v_active, v_max)); end if;
  end if;

  begin
    insert into bookings(date, hour, room_id, teacher_id, student_id, note, source)
    values (p_date, p_hour, p_room, p_teacher, p_student, left(coalesce(p_note, ''), 200), p_source)
    returning id into v_id;
  exception when unique_violation then
    get stacked diagnostics v_con = constraint_name;
    if v_con = 'uq_room_slot' then perform _err(format('%s è appena stata prenotata da qualcun altro. Scegli un''altra sala.', v_room.name));
    elsif v_con = 'uq_teacher_slot' then perform _err(format('%s è già impegnato a quell''ora. Scegli un altro insegnante.', v_teacher.name));
    elsif v_con = 'uq_student_slot' then perform _err('Hai già una lezione prenotata a quell''ora.');
    else raise; end if;
  end;
  return _booking_json(v_id);
end $$;

create or replace function _booking_json(p_id bigint) returns jsonb language sql stable security definer set search_path = public as $$
  select jsonb_build_object('id', b.id, 'date', b.date, 'hour', b.hour, 'status', b.status, 'source', b.source, 'note', b.note,
    'room_id', b.room_id, 'room', r.name, 'teacher_id', b.teacher_id, 'teacher', t.name, 'teacher_style', t.style,
    'student_id', s.id, 'student_name', s.name, 'student_phone', s.phone, 'wa_consent', s.wa_consent,
    'created_at', b.created_at, 'cancelled_by', b.cancelled_by, 'gcal_event_id', b.gcal_event_id,
    'outlook_event_id', b.outlook_event_id, 'sync_error', b.sync_error)
  from bookings b join rooms r on r.id = b.room_id join teachers t on t.id = b.teacher_id join students s on s.id = b.student_id
  where b.id = p_id
$$;

-- by: 'allievo' | 'segreteria' | 'whatsapp'. Gli allievi rispettano il preavviso minimo.
create or replace function _cancel_booking(p_id bigint, p_by text, p_student bigint default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare b bookings; v_limit int := _setting_int('cancel_hours');
begin
  select * into b from bookings where id = p_id for update;
  if not found or b.status <> 'confermata' then perform _err('Prenotazione non trovata o già annullata.'); end if;
  if p_by <> 'segreteria' then
    if b.student_id is distinct from p_student then perform _err('Prenotazione non trovata.'); end if;
    if _slot_start(b.date, b.hour) <= now() then perform _err('La lezione è già iniziata o passata.'); end if;
    if _slot_start(b.date, b.hour) - now() < make_interval(hours => v_limit) then
      perform _err(format('Si può annullare fino a %s ore prima. Per annullare ora contatta la segreteria.', v_limit));
    end if;
  end if;
  update bookings set status = 'annullata', cancelled_at = now(), cancelled_by = p_by where id = p_id;
  return _booking_json(p_id);
end $$;

create or replace function _student_bookings(p_student bigint) returns jsonb language sql stable security definer set search_path = public as $$
  with x as (
    select b.id, b.date, b.hour, b.note, b.status, b.room_id, b.teacher_id, r.name as room_name,
           t.name as teacher_name, t.style as teacher_style, t.color as teacher_color,
           (b.status = 'confermata' and _slot_start(b.date, b.hour) > now()) as upcoming
    from bookings b join rooms r on r.id = b.room_id join teachers t on t.id = b.teacher_id
    where b.student_id = p_student)
  select jsonb_build_object(
    'upcoming', coalesce((select jsonb_agg(to_jsonb(x) - 'upcoming' order by date, hour) from x where upcoming), '[]'),
    'past', coalesce((select jsonb_agg(to_jsonb(y) - 'upcoming' order by date desc, hour desc)
                      from (select * from x where not upcoming order by date desc, hour desc limit 50) y), '[]'))
$$;

-- coda eventi per Edge Functions (calendari, WhatsApp)
create or replace function _kick_worker() returns void language plpgsql security definer set search_path = public as $$
begin
  -- chiama subito la Edge Function "worker" se pg_net e i segreti in Vault sono configurati (vedi cron.sql)
  if to_regprocedure('net.http_post(text,jsonb,jsonb,jsonb,integer)') is null or to_regclass('vault.decrypted_secrets') is null then return; end if;
  execute $q$
    select net.http_post(
      url := (select decrypted_secret from vault.decrypted_secrets where name = 'project_url') || '/functions/v1/worker',
      headers := jsonb_build_object('Content-Type', 'application/json',
                 'x-worker-secret', (select decrypted_secret from vault.decrypted_secrets where name = 'worker_secret')),
      body := '{}'::jsonb)
    where exists (select 1 from vault.decrypted_secrets where name = 'project_url')
  $q$;
exception when others then null;  -- una prenotazione non deve mai fallire per colpa delle notifiche
end $$;

create or replace function _on_booking_change() returns trigger language plpgsql security definer set search_path = public as $$
declare v_consent boolean;
begin
  select wa_consent into v_consent from students where id = new.student_id;
  if tg_op = 'INSERT' then
    insert into outbox(kind, booking_id) values ('cal_sync', new.id);
    if v_consent and new.source <> 'whatsapp' then insert into outbox(kind, booking_id) values ('wa_confirm', new.id); end if;
  elsif new.status = 'annullata' and old.status = 'confermata' then
    insert into outbox(kind, booking_id) values ('cal_sync', new.id);
    if v_consent and coalesce(new.cancelled_by, '') <> 'whatsapp' then insert into outbox(kind, booking_id) values ('wa_cancel', new.id); end if;
  else
    return new;
  end if;
  perform _kick_worker();
  return new;
end $$;
