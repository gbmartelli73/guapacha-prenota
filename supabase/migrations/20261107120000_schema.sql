      select r.id into v_room from rooms r where r.active and (r.name ~* ('(^|\D)' || (p_input->>'sala') || '(\D|$)')) order by r.sort limit 1;
      if v_room is null or not exists (select 1 from jsonb_array_elements(g->'cells') c where (c->>'hour')::int = v_hour
             and (c->>'room_id')::bigint = v_room and c->>'status' = 'free' and c->'teachers' @> to_jsonb(t.id)) then
        return jsonb_build_object('errore', format('La sala %s non è libera a quell''ora con %s.', p_input->>'sala', t.name));
      end if;
    else
      select (c->>'room_id')::bigint into v_room from jsonb_array_elements(g->'cells') c
       where (c->>'hour')::int = v_hour and c->>'status' = 'free' and c->'teachers' @> to_jsonb(t.id) limit 1;
      if v_room is null then return jsonb_build_object('errore', format('%s non è disponibile %s alle %s.', t.name, _fmt_date(v_date), _fmt_hour(v_hour))); end if;
    end if;
    b := _create_booking(v_date, v_hour, v_room, t.id, s.id, coalesce(p_input->>'nota', ''), 'whatsapp', false, false);
    update students set wa_consent = true where id = s.id;
    return jsonb_build_object('prenotata', true, 'codice', b->'id', 'giorno', _fmt_date(v_date), 'ora', _fmt_hour(v_hour), 'sala', b->'room', 'insegnante', b->'teacher');

  elsif p_tool = 'le_mie_lezioni' then
    return jsonb_build_object('lezioni', coalesce((select jsonb_agg(jsonb_build_object('codice', x->'id', 'giorno', _fmt_date((x->>'date')::date),
      'ora', _fmt_hour((x->>'hour')::int), 'sala', x->'room_name', 'insegnante', x->'teacher_name'))
      from jsonb_array_elements(_student_bookings(s.id)->'upcoming') x), '[]'));

  elsif p_tool = 'annulla' then
    b := _cancel_booking((p_input->>'codice')::bigint, 'whatsapp', s.id);
    return jsonb_build_object('annullata', true, 'giorno', _fmt_date((b->>'date')::date), 'ora', _fmt_hour((b->>'hour')::int), 'sala', b->'room');

  elsif p_tool = 'salva_nome' then
    if length(trim(coalesce(p_input->>'nome', ''))) < 2 then return jsonb_build_object('errore', 'Nome non valido.'); end if;
    update students set name = left(trim(p_input->>'nome'), 80) where id = s.id;
    return jsonb_build_object('salvato', true);
  end if;
  return jsonb_build_object('errore', 'Strumento sconosciuto.');
exception
  when sqlstate 'P0001' then return jsonb_build_object('errore', sqlerrm);
  when invalid_datetime_format or datetime_field_overflow or invalid_text_representation then return jsonb_build_object('errore', 'Data o ora non valida: usa AAAA-MM-GG e un''ora intera.');
end $$;

create or replace function bot_seen(p_msg_id text) returns boolean language plpgsql security definer set search_path = public as $$
begin
  delete from wa_inbox where received_at < now() - interval '7 days';
  insert into wa_inbox(id) values (p_msg_id) on conflict do nothing;
  return not found;   -- true = già elaborato
end $$;

create or replace function bot_history(p_phone text) returns jsonb language sql stable security definer set search_path = public as $$
  select coalesce((select history from wa_sessions where phone = _norm_phone(p_phone) and updated_at > now() - interval '12 hours'), '[]')
$$;
create or replace function bot_save_history(p_phone text, p_history jsonb) returns void language sql security definer set search_path = public as $$
  insert into wa_sessions(phone, history, updated_at) values (_norm_phone(p_phone), p_history, now())
  on conflict (phone) do update set history = excluded.history, updated_at = now()
$$;

-- ============================================ worker (solo service_role)
create or replace function worker_claim(p_limit int default 20) returns jsonb language plpgsql security definer set search_path = public as $$
declare v jsonb;
begin
  -- promemoria: accoda quelli entro reminder_hours (non per lezioni prenotate nelle ultime 6 ore)
  with due as (
    update bookings b set reminded_at = now()
     where b.status = 'confermata' and b.reminded_at is null
       and _slot_start(b.date, b.hour) between now() + interval '30 minutes' and now() + make_interval(hours => _setting_int('reminder_hours'))
       and b.date between _today() and _today() + 3
    returning b.id, b.student_id, b.created_at)
  insert into outbox(kind, booking_id)
    select 'wa_reminder', d.id from due d join students s on s.id = d.student_id
     where s.wa_consent and d.created_at < now() - interval '6 hours';

  -- prende in carico i lavori pronti; se il worker si interrompe, vengono ripresi dopo il ritardo crescente
  with c as (
    select id from outbox where done_at is null and next_at <= now() and attempts < 8
    order by id limit p_limit for update skip locked),
  u as (
    update outbox o set attempts = o.attempts + 1, next_at = now() + make_interval(mins => least((2 ^ o.attempts)::int * 2, 360))
      from c where o.id = c.id
    returning o.id, o.kind, o.attempts, o.booking_id)
  select coalesce(jsonb_agg(jsonb_build_object('id', u.id, 'kind', u.kind, 'attempts', u.attempts, 'booking', _booking_json(u.booking_id)) order by u.id), '[]')
    into v from u;
  return v;
end $$;

create or replace function worker_done(p_id bigint, p_error text default null) returns void language sql security definer set search_path = public as $$
  update outbox set done_at = case when p_error is null then now() end, last_error = p_error where id = p_id
$$;

create or replace function worker_set_sync(p_booking bigint, p_gcal text, p_outlook text, p_error text) returns void language sql security definer set search_path = public as $$
  update bookings set gcal_event_id = p_gcal, outlook_event_id = p_outlook, sync_error = p_error where id = p_booking
$$;

create or replace function worker_heartbeat(p_google boolean, p_outlook boolean, p_whatsapp boolean, p_bot boolean) returns void
language plpgsql security definer set search_path = public as $$
begin
  insert into settings(key, value) values ('int_google', p_google::text), ('int_outlook', p_outlook::text), ('int_whatsapp', p_whatsapp::text),
    ('int_bot', p_bot::text), ('worker_last_run', to_char(now() at time zone _tz(), 'YYYY-MM-DD HH24:MI'))
  on conflict (key) do update set value = excluded.value;
  update settings set value = (p_whatsapp and p_bot)::text where key = 'bot_enabled';
end $$;

