-- ---------------------------------------------------------------- tabelle
create table if not exists settings (key text primary key, value text not null);

create table if not exists rooms (
  id bigint generated by default as identity primary key,
  name text not null, info text not null default '', sort int not null default 0, active boolean not null default true
);
create table if not exists teachers (
  id bigint generated by default as identity primary key,
  name text not null, style text not null default '', color text not null default '#6F5FCB',
  phone text not null default '', active boolean not null default true
);
-- turni settimanali: weekday 0 = domenica … 6 = sabato, ore intere [start_hour, end_hour)
create table if not exists shifts (
  id bigint generated by default as identity primary key,
  teacher_id bigint not null references teachers(id) on delete cascade,
  weekday int not null check (weekday between 0 and 6),
  start_hour int not null check (start_hour between 0 and 23),
  end_hour int not null check (end_hour between 1 and 24 and end_hour > start_hour)
);
create table if not exists opening (
  weekday int primary key check (weekday between 0 and 6),
  start_hour int, end_hour int,
  check ((start_hour is null and end_hour is null) or (start_hour >= 0 and end_hour <= 24 and end_hour > start_hour))
);
-- blocchi: chiusure, festività, corsi collettivi, saggi, assenze.
-- room_id null e teacher_id null = tutta la scuola; solo teacher_id = assenza dell'insegnante.
create table if not exists blocks (
  id bigint generated by default as identity primary key,
  date date not null, start_hour int not null, end_hour int not null check (end_hour > start_hour),
  room_id bigint references rooms(id) on delete cascade,
  teacher_id bigint references teachers(id) on delete cascade,
  title text not null default 'Non disponibile'
);
create index if not exists blocks_date on blocks(date);

create table if not exists students (
  id bigint generated by default as identity primary key,
  user_id uuid unique references auth.users(id) on delete set null,
  phone text not null unique,               -- E.164 senza "+", es. 393331234567
  name text not null default '',
  wa_consent boolean not null default false,
  notes text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists staff (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists bookings (
  id bigint generated by default as identity primary key,
  date date not null, hour int not null check (hour between 0 and 23),
  room_id bigint not null references rooms(id),
  teacher_id bigint not null references teachers(id),
  student_id bigint not null references students(id),
  note text not null default '',
  status text not null default 'confermata' check (status in ('confermata','annullata')),
  source text not null default 'app' check (source in ('app','segreteria','whatsapp')),
  created_at timestamptz not null default now(),
  cancelled_at timestamptz, cancelled_by text,
  reminded_at timestamptz,
  gcal_event_id text, outlook_event_id text, sync_error text
);
-- impossibili i doppioni, anche con richieste simultanee
create unique index if not exists uq_room_slot    on bookings(date, hour, room_id)    where status = 'confermata';
create unique index if not exists uq_teacher_slot on bookings(date, hour, teacher_id) where status = 'confermata';
create unique index if not exists uq_student_slot on bookings(date, hour, student_id) where status = 'confermata';
create index if not exists bookings_date on bookings(date);
create index if not exists bookings_student on bookings(student_id);

-- coda di lavori per le Edge Functions (calendari e messaggi WhatsApp)
create table if not exists outbox (
  id bigint generated by default as identity primary key,
  kind text not null check (kind in ('cal_sync','wa_confirm','wa_cancel','wa_reminder')),
  booking_id bigint not null references bookings(id) on delete cascade,
  created_at timestamptz not null default now(),
  next_at timestamptz not null default now(),
  attempts int not null default 0,
  done_at timestamptz, last_error text
);
create index if not exists outbox_pending on outbox(next_at) where done_at is null;

create table if not exists wa_sessions (phone text primary key, history jsonb not null default '[]', updated_at timestamptz not null default now());
create table if not exists wa_inbox (id text primary key, received_at timestamptz not null default now());

