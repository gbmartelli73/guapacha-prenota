    if not found then perform _err('Insegnante non trovato.'); end if;
  end if;
  if p_shifts is not null then
    delete from shifts where teacher_id = v_id;
    for sh in select * from jsonb_array_elements(p_shifts) loop
      if (sh->>'weekday')::int not between 0 and 6 or (sh->>'start_hour')::int not between 0 and 23
